  private SystemRolePermissions() {}

  /**
   * The permissions held by a system role, or an empty set for an unrecognised role code.
   *
   * <p>Empty rather than an exception: an unknown role grants nothing, which is the deny-by-default
   * answer (BR-IAM-002). Throwing would turn a stale role row into a 500 on every request the
   * holder makes.
   */
  public static Set<String> permissionsOf(String roleCode) {
    return BY_ROLE.getOrDefault(roleCode, Set.of());
  }

  /** Every role code this class knows about. */
  public static Set<String> roleCodes() {
    return BY_ROLE.keySet();
  }
